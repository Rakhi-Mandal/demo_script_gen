def copy_allure_results_to_run_dir(project_path: Path, run_allure_dir: Path, run_started_at: float) -> None:
    default_allure_dir = project_path / "allure-results"
    if not default_allure_dir.exists() or not default_allure_dir.is_dir():
        return

    copied_any = False
    run_allure_dir.mkdir(parents=True, exist_ok=True)
    for item in default_allure_dir.iterdir():
        if not item.is_file():
            continue
        with suppress(OSError):
            if item.stat().st_mtime + 1 < run_started_at:
                continue
        shutil.copy2(item, run_allure_dir / item.name)
        copied_any = True

    if not copied_any:
        with suppress(OSError):
            run_allure_dir.rmdir()


async def generate_allure_html_report(allure_results_dir: Path, allure_report_dir: Path, run_env: dict[str, str]) -> tuple[bool, str]:
    has_result_files = (
        allure_results_dir.exists()
        and any(item.is_file() and item.name != ".gitignore" for item in allure_results_dir.iterdir())
    )
    if not has_result_files:
        return False, "No Allure result files found."

    try:
        process = await asyncio.create_subprocess_exec(
            resolve_command("allure"),
            "generate",
            str(allure_results_dir),
            "-o",
            str(allure_report_dir),
            "--clean",
            cwd=str(allure_results_dir.parent),
            env=run_env,
            stdout=asyncio.subprocess.PIPE,
            stderr=asyncio.subprocess.STDOUT,
        )
    except Exception as exc:
        return False, f"Allure HTML generation skipped: {exc}"

    output = ""
    if process.stdout is not None:
        chunks = await process.stdout.read()
        output = chunks.decode(errors="replace").strip()
    await process.wait()
    return process.returncode == 0, output or f"allure generate exited with code {process.returncode}"


