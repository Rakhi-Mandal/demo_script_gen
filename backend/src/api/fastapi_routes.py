@router.websocket("/api/jenkins/watch/{run_id}")
async def jenkins_watch_ws(websocket: WebSocket, run_id: str) -> None:
    """
    Stream a single 'done' message when the Jenkins run finishes.
    Client connects, backend polls DB every 3s, sends progress heartbeats,
    and sends {type:'done', ...} once status is passed/failed.
    Times out after ~30 min.
    """
    await websocket.accept()
    from ..db.database import get_jenkins_run_info

    max_iterations = 600  # 30 min at 3s intervals
    try:
        for _ in range(max_iterations):
            try:
                info = get_jenkins_run_info(run_id)
            except Exception as exc:
                await websocket.send_json({"type": "error", "message": f"DB lookup failed: {exc}"})
                return

            if not info:
                await websocket.send_json({"type": "error", "message": f"Run {run_id} not found."})
                return

            status = (info.get("status") or "").lower()
            if status in ("passed", "failed"):
                # Finished - send full info + close
                await websocket.send_json({
                    "type": "done",
                    "ok": True,
                    **info,
                })
                return

            # Still running - send heartbeat (optional, keeps client informed)
            await websocket.send_json({
                "type": "progress",
                "status": status or "running",
                "run_id": info.get("run_id"),
                "jenkins_build_url": info.get("jenkins_build_url"),
            })

            await asyncio.sleep(3)

        await websocket.send_json({"type": "timeout", "message": "Watch timed out after 30 min."})

    except WebSocketDisconnect:
        return
    except Exception as exc:
        with suppress(Exception):
            await websocket.send_json({"type": "error", "message": str(exc)})
    finally:
        with suppress(Exception):
            await websocket.close()


