async def regenerate_healed_spec(plain_spec_path: Path) -> dict[str, Any]:
    """
    Regenerate the .healed.spec.js for a given plain .spec.js by invoking
    the regenerate-healed.js Node script (which calls the heal-wrapper LLM).
 
    Returns a dict like:
      { "ok": True, "healedPath": "..." }
      { "ok": False, "error": "..." }
 
    Only regenerates for files that look like a plain spec under sanity/
    or regression/. Returns {"ok": False, "skipped": True} for other files.
    """
    plain_path = Path(plain_spec_path).resolve()
 
    # Only regenerate for .spec.js files under sanity/ or regression/
    if plain_path.suffix != ".js" or not plain_path.name.endswith(".spec.js"):
        return {"ok": False, "skipped": True, "reason": "Not a .spec.js file."}
    if plain_path.name.endswith(".healed.spec.js"):
        return {"ok": False, "skipped": True, "reason": "File is already a healed spec."}
 
    suite_name = plain_path.parent.name.lower()
    if suite_name not in ("sanity", "regression"):
        return {"ok": False, "skipped": True, "reason": "Not under sanity/ or regression/."}
 
    # Locate the Node script
    backend_root = Path(__file__).resolve().parents[2]
    node_script = backend_root / "src" / "script_generator" / "regenerate-healed.js"
    if not node_script.exists():
        return {"ok": False, "error": f"regenerate-healed.js not found at {node_script}"}
 
    # Run the Node script asynchronously
    cmd = ["node", str(node_script), f"--plain={plain_path}"]
 
    try:
        process = await asyncio.create_subprocess_exec(
            *cmd,
            cwd=str(backend_root),
            stdout=asyncio.subprocess.PIPE,
            stderr=asyncio.subprocess.PIPE,
        )
        stdout_bytes, stderr_bytes = await asyncio.wait_for(
            process.communicate(),
            timeout=300,  # 300s should cover even slow LLM responses
        )
    except asyncio.TimeoutError:
        try:
            process.kill()
        except Exception:
            pass
        return {"ok": False, "error": "Heal regeneration timed out after 60s."}
    except Exception as exc:
        return {"ok": False, "error": f"Failed to spawn regenerate-healed.js: {exc}"}
 
    stdout_text = stdout_bytes.decode("utf-8", errors="replace").strip()
    stderr_text = stderr_bytes.decode("utf-8", errors="replace").strip()
 
    # The Node script prints a single-line JSON result on stdout
    if stdout_text:
        try:
            # The result may be the last line in stdout (logs go to stderr)
            last_line = stdout_text.splitlines()[-1]
            return json.loads(last_line)
        except json.JSONDecodeError:
            pass
 
    return {
        "ok": False,
        "error": f"regenerate-healed.js failed (exit {process.returncode}): {stderr_text or stdout_text or 'no output'}",
    }

@router.post("/api/projects/file", tags=["Projects"], summary="Save an editable project file")
async def save_project_file_endpoint(body: ProjectFileSaveBody) -> dict[str, Any]:
    file_path = resolve_editable_project_file(body.filePath or "")
    file_path.write_text(body.content or "", encoding="utf-8")

    # Regenerate the healed spec if this is a plain spec under sanity/regression.
    # Errors are reported but do not fail the save.
    print(f"[heal-regen] STARTING for file={file_path}")
    heal_result = await regenerate_healed_spec(file_path)
    print(f"[heal-regen] RESULT={heal_result}")

    # Mark the test_case as modified in the DB so we know the spec was edited
    try:
        from ..db.database import mark_spec_modified, db_cursor
        from pathlib import Path as _Path

        # Find which project this file belongs to by matching path prefix
        with db_cursor() as cur:
            cur.execute("SELECT path FROM projects")
            projects = cur.fetchall()
        matched_project_path = None
        file_path_str = str(file_path).replace("\\", "/")
        for proj in projects:
            proj_path = str(proj["path"]).replace("\\", "/").rstrip("/")
            if file_path_str.startswith(proj_path + "/") or file_path_str.startswith(proj_path + "\\"):
                matched_project_path = str(proj["path"])
                break

        if matched_project_path:
            try:
                spec_relpath = str(_Path(file_path).relative_to(_Path(matched_project_path))).replace("\\", "/")
            except ValueError:
                spec_relpath = file_path_str
            updated = mark_spec_modified(
                project_path=matched_project_path,
                spec_relpath=spec_relpath,
                test_name=None,  # update all matching specs
                modified=True,
            )
            print(f"[db] mark_spec_modified: project={matched_project_path}, spec={spec_relpath}, rows_updated={updated}")
    except Exception as _db_exc:
        print(f"[db] Failed to mark spec modified: {_db_exc}")

    response: dict[str, Any] = {
        "ok": True,
        "filePath": str(file_path),
        "message": "Script saved.",
    }

    if heal_result.get("ok"):
        response["healedPath"] = heal_result.get("healedPath")
        response["healedRegenerated"] = True
        response["message"] = "Script saved. Healed version regenerated."
    elif heal_result.get("skipped"):
        response["healedRegenerated"] = False
        response["healSkipped"] = True
        response["healSkipReason"] = heal_result.get("reason", "")
    else:
        response["healedRegenerated"] = False
        response["healError"] = heal_result.get("error", "Unknown heal-regen error.")
        response["message"] = "Script saved. (Healed version was NOT updated.)"

    return response


