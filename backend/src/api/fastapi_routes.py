async def trigger_jenkins_suite(test_type: str, payload: dict[str, Any]) -> dict[str, Any]:
    jenkins_url = _jenkins_env_value("JENKINS_URL")

    project_path = str(payload.get("projectPath") or "").strip()

    project_meta = {}
    if project_path:
        try:
            project_meta = read_project_metadata(Path(project_path))
        except Exception:
            project_meta = {}

    job_name = str(
        payload.get("jobName")
        or project_meta.get("jenkinsJobName")
        or ""
    ).strip()

    if not jenkins_url or not job_name:
        raise HTTPException(
            status_code=400,
            detail="Select a project and enter a Jenkins job name in the UI before using the Jenkins run button.",
        )

    job_path = "/job/".join(
        quote(part, safe="")
        for part in job_name.split("/")
        if part.strip()
    )

    build_url = f"{jenkins_url.rstrip('/')}/job/{job_path}/buildWithParameters"

    query = {
         "EXECUTION_MODE": "suite",
        "TARGET": test_type,
        "BROWSER": str(payload.get("browser") or "chromium"),
        "HEADED": "true" if bool(payload.get("headed")) else "false",
        "EXECUTION": str(payload.get("execution") or "parallel"),
        "WORKERS": str(payload.get("workers") or "4"),
    }

    if project_path:
        query["PROJECT_PATH"] = project_path

    request_body = urlencode(query).encode("utf-8")

    headers = {
        "Content-Type": "application/x-www-form-urlencoded"
    }

    auth_header = _jenkins_auth_header()

    if auth_header:
        headers["Authorization"] = auth_header

    crumb_url = _jenkins_env_value("JENKINS_CRUMB_URL")

    if not crumb_url:
        crumb_url = f"{jenkins_url.rstrip('/')}/crumbIssuer/api/json"

    loop = asyncio.get_running_loop()

    def _do_request() -> dict[str, Any]:

        cookie_jar = CookieJar()

        opener = build_opener(
            HTTPCookieProcessor(cookie_jar)
        )

        try:
            # FETCH CRUMB
            crumb_request = UrlRequest(crumb_url)

            if auth_header:
                crumb_request.add_header(
                    "Authorization",
                    auth_header
                )

            with opener.open(crumb_request, timeout=20) as response:

                crumb_response_text = response.read().decode("utf-8")

                print("CRUMB RESPONSE:", crumb_response_text)

                crumb_data = json.loads(crumb_response_text)

                crumb_header_name = str(
                    crumb_data.get("crumbRequestField") or ""
                ).strip()

                crumb_header_value = str(
                    crumb_data.get("crumb") or ""
                ).strip()

                print("CRUMB HEADER:", crumb_header_name)
                print("CRUMB VALUE:", crumb_header_value)

                if crumb_header_name and crumb_header_value:
                    headers[crumb_header_name] = crumb_header_value

            print("BUILD URL:", build_url)
            print("REQUEST HEADERS:", headers)

            request = UrlRequest(
                build_url,
                data=request_body,
                headers=headers,
                method="POST"
            )

            with opener.open(request, timeout=30) as response:

                headers_map = {
                    key: value
                    for key, value in response.headers.items()
                }

                return {
                    "status": response.status,
                    "headers": headers_map,
                    "body": response.read().decode(
                        "utf-8",
                        errors="replace"
                    ),
                    "queueUrl": headers_map.get("Location")
                    or headers_map.get("location")
                    or "",
                }

        except HTTPError as exc:

            body = (
                exc.read().decode("utf-8", errors="replace")
                if hasattr(exc, "read")
                else ""
            )

            raise HTTPException(
                status_code=exc.code,
                detail=body or str(exc)
            ) from exc

        except URLError as exc:

            raise HTTPException(
                status_code=502,
                detail=f"Unable to reach Jenkins: {exc.reason}"
            ) from exc

        except Exception as exc:

            raise HTTPException(
                status_code=500,
                detail=f"Jenkins trigger failed: {str(exc)}"
            ) from exc

    return await loop.run_in_executor(None, _do_request)


async def create_jenkins_job(payload: dict[str, Any]) -> dict[str, Any]:

    jenkins_url = _jenkins_env_value("JENKINS_URL")

    if not jenkins_url:
        raise HTTPException(
            status_code=400,
            detail="Set JENKINS_URL in the backend environment before creating a Jenkins job."
        )

    project_path = str(payload.get("projectPath") or "").strip()

    project_meta = {}

    if project_path:
        try:
            project_meta = read_project_metadata(Path(project_path))
        except Exception:
            project_meta = {}

    inferred_job_name = Path(project_path).name if project_path else ""

    job_name = str(
        payload.get("jobName")
        or project_meta.get("jenkinsJobName")
        or inferred_job_name
    ).strip()

    repo_url = str(
        payload.get("githubUrl")
        or project_meta.get("githubUrl")
        or ""
    ).strip()

    branch_name = str(
        payload.get("branchName")
        or "main"
    ).strip() or "main"

    jenkinsfile_path = str(
        payload.get("jenkinsfilePath")
        or "Jenkinsfile"
    ).strip() or "Jenkinsfile"

    if not job_name:
        raise HTTPException(
            status_code=400,
            detail="A Jenkins job name is required."
        )

    if not repo_url:
        raise HTTPException(
            status_code=400,
            detail="Provide a GitHub URL for the selected project before creating the Jenkins job."
        )

    create_url = (
        f"{jenkins_url.rstrip('/')}"
        f"/createItem?name={quote(job_name, safe='')}"
    )

    headers = {
        "Content-Type": "application/xml"
    }

    auth_header = _jenkins_auth_header()

    if auth_header:
        headers["Authorization"] = auth_header

    crumb_url = _jenkins_env_value("JENKINS_CRUMB_URL")

    if not crumb_url:
        crumb_url = f"{jenkins_url.rstrip('/')}/crumbIssuer/api/json"

    config_xml = _jenkins_job_config_xml(
        repo_url,
        branch_name,
        jenkinsfile_path
    ).encode("utf-8")

    # === Existence check: does this Jenkins job already exist? ===
    check_url = f"{jenkins_url.rstrip('/')}/job/{quote(job_name, safe='')}/api/json"
    check_headers = {}
    if auth_header:
        check_headers["Authorization"] = auth_header

    def _do_check_exists() -> bool:
        try:
            check_req = UrlRequest(check_url, headers=check_headers)
            with urlopen(check_req, timeout=15) as response:
                if response.status == 200:
                    return True
        except HTTPError as e:
            if e.code == 404:
                return False
            # Some other HTTP error — log and proceed (don't block creation)
            print(f"[jenkins] existence check returned HTTP {e.code}: {e.reason}")
            return False
        except Exception as e:
            print(f"[jenkins] existence check failed: {e}")
            return False
        return False

    loop = asyncio.get_running_loop()
    already_exists = await loop.run_in_executor(None, _do_check_exists)
    if already_exists:
        raise HTTPException(
            status_code=409,
            detail=f"A Jenkins job named '{job_name}' already exists. Choose a different name or delete the existing job."
        )

    def _do_request() -> dict[str, Any]:

        cookie_jar = CookieJar()

        opener = build_opener(
            HTTPCookieProcessor(cookie_jar)
        )

        try:
            # FETCH CRUMB
            crumb_request = UrlRequest(crumb_url)

            if auth_header:
                crumb_request.add_header(
                    "Authorization",
                    auth_header
                )

            with opener.open(crumb_request, timeout=20) as response:

                crumb_response_text = response.read().decode("utf-8")

                print("CRUMB RESPONSE:", crumb_response_text)

                crumb_data = json.loads(crumb_response_text)

                crumb_header_name = str(
                    crumb_data.get("crumbRequestField") or ""
                ).strip()

                crumb_header_value = str(
                    crumb_data.get("crumb") or ""
                ).strip()

                print("CRUMB HEADER:", crumb_header_name)
                print("CRUMB VALUE:", crumb_header_value)

                if crumb_header_name and crumb_header_value:
                    headers[crumb_header_name] = crumb_header_value

            print("CREATE URL:", create_url)
            print("REQUEST HEADERS:", headers)

            request = UrlRequest(
                create_url,
                data=config_xml,
                headers=headers,
                method="POST"
            )

            with opener.open(request, timeout=30) as response:

                headers_map = {
                    key: value
                    for key, value in response.headers.items()
                }

                if project_path and job_name:

                    try:
                        existing_meta = read_project_metadata(
                            Path(project_path)
                        )
                    except Exception:
                        existing_meta = {}

                    existing_meta.update({
                        "githubUrl": repo_url,
                        "jenkinsJobName": job_name,
                    })

                    from .fastapi_support import write_project_metadata

                    write_project_metadata(
                        Path(project_path),
                        existing_meta
                    )

                return {
                    "status": response.status,
                    "headers": headers_map,
                    "body": response.read().decode(
                        "utf-8",
                        errors="replace"
                    ),
                }

        except HTTPError as exc:

            body = (
                exc.read().decode("utf-8", errors="replace")
                if hasattr(exc, "read")
                else ""
            )

            raise HTTPException(
                status_code=exc.code,
                detail=body or str(exc)
            ) from exc

        except URLError as exc:

            raise HTTPException(
                status_code=502,
                detail=f"Unable to reach Jenkins: {exc.reason}"
            ) from exc

        except Exception as exc:

            raise HTTPException(
                status_code=500,
                detail=f"Jenkins job creation failed: {str(exc)}"
            ) from exc

    return await loop.run_in_executor(None, _do_request)


async def poll_jenkins_build(
    run_id: str,
    queue_url: str,
    project_path: str,
    job_name: str,
    max_iterations: int = 240,  # 240 * 5s = 20 minutes max
) -> None:
    """
    Background task: poll Jenkins for build status, then update DB.
    1) Poll the queue URL until Jenkins assigns a build number
    2) Then poll the build's API URL until it finishes
    3) Update test_runs with final status and build URL
    """
    jenkins_url = _jenkins_env_value("JENKINS_URL")
    if not jenkins_url:
        return
    auth_header = _jenkins_auth_header()

    def _fetch_json(url: str) -> dict[str, Any] | None:
        try:
            req = UrlRequest(url.rstrip("/") + "/api/json")
            if auth_header:
                req.add_header("Authorization", auth_header)
            with urlopen(req, timeout=15) as response:
                return json.loads(response.read().decode("utf-8"))
        except Exception as e:
            print(f"[jenkins-poll] fetch_json {url} failed: {e}")
            return None

    loop = asyncio.get_running_loop()

    # Step 1: poll queue URL until we get a build number
    build_url: str = ""
    for _ in range(max_iterations):
        await asyncio.sleep(5)
        data = await loop.run_in_executor(None, _fetch_json, queue_url)
        if data and isinstance(data.get("executable"), dict):
            build_url = data["executable"].get("url") or ""
            if build_url:
                print(f"[jenkins-poll] build assigned: {build_url}")
                # Save the build URL in DB (replace queue URL)
                try:
                    from ..db.database import set_jenkins_info
                    set_jenkins_info(run_id=run_id, jenkins_build_url=build_url)
                except Exception as _e:
                    print(f"[jenkins-poll] save build_url failed: {_e}")
                break
            else:
                continue

    if not build_url:
        print(f"[jenkins-poll] queue did not assign a build for run_id={run_id}")
        try:
            from ..db.database import finish_test_run
            finish_test_run(run_id=run_id, status="failed",
                            total_tests=0, passed_count=0, failed_count=0, skipped_count=0)
        except Exception:
            pass
        return

    # Step 2: poll build URL until it finishes
    for _ in range(max_iterations):
        await asyncio.sleep(5)
        data = await loop.run_in_executor(None, _fetch_json, build_url)
        if data is None:
            continue
        building = bool(data.get("building"))
        if building:
            continue
        # Build finished
        result_status = (data.get("result") or "UNKNOWN").upper()
        playwright_status = "passed" if result_status == "SUCCESS" else "failed"
        print(f"[jenkins-poll] build finished: run_id={run_id} jenkins_result={result_status} -> {playwright_status}")

        # Discover report URLs.
        # PREFER Jenkins plugin URLs (which properly serve SPA reports with all assets)
        # over raw /artifact/ URLs (which cause blank pages due to broken relative asset paths).
        html_report_url = ""
        allure_report_url = ""

        def _head_ok(url: str) -> bool:
            try:
                req = UrlRequest(url, method="HEAD")
                if auth_header:
                    req.add_header("Authorization", auth_header)
                with urlopen(req, timeout=5) as resp:
                    return resp.status < 400
            except Exception:
                return False

        # 1. Try Allure Jenkins plugin URL first
        allure_plugin_url = build_url.rstrip("/") + "/allure/"
        if _head_ok(allure_plugin_url):
            allure_report_url = allure_plugin_url

        # 2. For Playwright HTML report, we intentionally skip publishHTML plugin URL
        #    because it wraps the report in an iframe/tab UI and Jenkins CSP blocks
        #    Playwright's inline scripts inside that wrapper.
        #    We use the raw /artifact/ URL below in step 3, which works if CSP is relaxed:
        #    Jenkins > Manage > Script Console:
        #      System.setProperty(\"hudson.model.DirectoryBrowserSupport.CSP\", \"\")

        # 3. Fall back to raw /artifact/ URLs if plugin URLs unavailable
        if not html_report_url or not allure_report_url:
            try:
                artifacts = data.get("artifacts") or []
                base_artifact_url = build_url.rstrip("/") + "/artifact/"
                for art in artifacts:
                    rel = (art.get("relativePath") or "").lower()
                    if not rel or not rel.endswith("index.html"):
                        continue
                    if not allure_report_url and "allure-report" in rel:
                        allure_report_url = base_artifact_url + art["relativePath"]
                    elif not html_report_url and ("playwright-report" in rel or "/html/" in rel):
                        html_report_url = base_artifact_url + art["relativePath"]
            except Exception as _art_exc:
                print(f"[jenkins-poll] artifact discovery failed: {_art_exc}")

        try:
            from ..db.database import finish_test_run, set_jenkins_info
            finish_test_run(
                run_id=run_id,
                status=playwright_status,
                total_tests=0,
                passed_count=0,
                failed_count=0,
                skipped_count=0,
            )
            set_jenkins_info(
                run_id=run_id,
                jenkins_html_report_url=html_report_url or None,
                jenkins_allure_report_url=allure_report_url or None,
            )
            print(f"[jenkins-poll] saved report URLs: html={html_report_url} allure={allure_report_url}")
        except Exception as _e:
            print(f"[jenkins-poll] finish_test_run failed: {_e}")
        return

    print(f"[jenkins-poll] build polling timed out for run_id={run_id}")



def _build_project_info_from_path(project_path) -> dict | None:
    """Look up project (id, name, path) from DB by its on-disk path."""
    if not project_path:
        return None
    try:
        from ..db.database import db_cursor
        ppath = str(project_path)
        with db_cursor() as cur:
            cur.execute("SELECT id, name, path FROM projects WHERE LOWER(path) = LOWER(%s) LIMIT 1", (ppath,))
            row = cur.fetchone()
        if row:
            return {"id": str(row["id"]), "name": row["name"], "path": row["path"]}
        # Not in DB - return path-only fallback
        from pathlib import Path as _Path
        return {"id": None, "name": _Path(ppath).name, "path": ppath}
    except Exception as exc:
        print(f"[projectInfo] lookup failed: {exc}")
        return None


