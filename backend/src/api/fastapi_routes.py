@router.post("/api/new-step-suggestions", tags=["Workflow"], summary="Suggest new Playwright steps")
async def new_step_suggestions(request: Request) -> dict[str, Any]:
    try:
        body = await request.json()
    except Exception:
        raise HTTPException(status_code=400, detail="Invalid JSON body")

    script_text = str(body.get("scriptText") or "").strip()
    if script_text:
        result = await run_new_step_suggester({
            "mode": "script",
            "scriptText": script_text,
            "category": str(body.get("category") or ""),
            "hintText": str(body.get("hintText") or ""),
        })
        return {"ok": True, "results": result.get("results", [])}

    line = body.get("line")
    line_number = body.get("lineNumber")
    all_lines = body.get("allLines")
    if line is None or line_number is None or all_lines is None:
        raise HTTPException(status_code=400, detail="Provide either scriptText or line, lineNumber, and allLines.")

    try:
        coerced_line_number = int(line_number)
    except Exception:
        raise HTTPException(status_code=400, detail="lineNumber must be an integer.")

    if not isinstance(all_lines, list):
        raise HTTPException(status_code=400, detail="allLines must be a list of script lines.")

    result = await run_new_step_suggester({
        "mode": "line",
        "line": str(line or ""),
        "lineNumber": coerced_line_number,
        "allLines": [str(item or "") for item in all_lines],
        "category": str(body.get("category") or ""),
        "hintText": str(body.get("hintText") or ""),
    })
    return {"ok": True, "results": [{"lineNumber": coerced_line_number, "line": str(line or ""), "category": result.get("category"), "reason": result.get("reason", ""), "suggestions": result.get("suggestions", [])}]}

