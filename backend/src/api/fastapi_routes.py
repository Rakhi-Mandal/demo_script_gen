@router.post("/api/projects/set-priority", tags=["Workflow"], summary="Set priority on a spec file by renaming it with a numeric prefix")
async def set_spec_priority(body: dict[str, Any]) -> dict[str, Any]:
    """
    Renames a spec file with the next available NN_ prefix within its suite folder.
    Priority is numbered per-folder (sanity has its own counter, regression has its own).
    If the file already has a NN_ prefix, returns the existing priority without changes.
    """
    spec_path_raw = str(body.get("specPath") or "").strip()
    if not spec_path_raw:
        raise HTTPException(status_code=400, detail="specPath is required")

    spec_path = Path(spec_path_raw)
    if not spec_path.exists():
        raise HTTPException(status_code=404, detail=f"Spec file not found: {spec_path_raw}")
    if not spec_path.is_file():
        raise HTTPException(status_code=400, detail=f"Path is not a file: {spec_path_raw}")

    suite_folder = spec_path.parent
    current_name = spec_path.name

    # Pattern matches files starting with two digits and underscore: e.g. "01_login.spec.js"
    prefix_pattern = re.compile(r"^(\d{2})_")

    # Check if already prioritized
    existing_match = prefix_pattern.match(current_name)
    if existing_match:
        existing_priority = int(existing_match.group(1))
        return {
            "ok": True,
            "alreadyPrioritized": True,
            "priority": existing_priority,
            "fileName": current_name,
            "filePath": str(spec_path),
            "message": f"File already has priority {existing_priority}",
        }

    # Find max existing prefix in this folder
    max_priority = 0
    for entry in suite_folder.iterdir():
        if entry.is_file() and entry.name.endswith(".spec.js"):
            m = prefix_pattern.match(entry.name)
            if m:
                n = int(m.group(1))
                if n > max_priority:
                    max_priority = n

    next_priority = max_priority + 1
    new_name = f"{next_priority:02d}_{current_name}"
    new_path = suite_folder / new_name

    if new_path.exists():
        raise HTTPException(
            status_code=409,
            detail=f"Cannot rename: target {new_name} already exists in {suite_folder}",
        )

    try:
        spec_path.rename(new_path)
    except OSError as exc:
        raise HTTPException(status_code=500, detail=f"Rename failed: {exc}") from exc

    print(f"PRIORITY SET: {current_name} -> {new_name} (priority {next_priority}) in {suite_folder}")

    return {
        "ok": True,
        "alreadyPrioritized": False,
        "priority": next_priority,
        "fileName": new_name,
        "filePath": str(new_path),
        "message": f"Set priority {next_priority} on {new_name}",
    }



def normalize_report_types(value: Any) -> list[str]:
    if value is None:
        return ["json", "html", "allure"]

    raw_items = value if isinstance(value, list) else [value]
    allowed = {"json", "html", "allure"}
    report_types: list[str] = []
    for item in raw_items:
        normalized = str(item or "").strip().lower()
        if normalized in allowed and normalized not in report_types:
            report_types.append(normalized)
    return report_types or ["json", "html", "allure"]


def ensure_report_types(value: list[str], required: list[str]) -> list[str]:
    report_types = list(value)
    for item in required:
        if item not in report_types:
            report_types.append(item)
    return report_types


def is_healed_run(spec_path: str, resolved_spec_path: Path | None = None, spec_name: str = "") -> bool:
    candidates = [spec_path or "", spec_name or ""]
    if resolved_spec_path:
        candidates.append(str(resolved_spec_path))

    for candidate in candidates:
        if not candidate:
            continue
        # Normalize both Windows and POSIX path separators
        normalized = str(candidate).replace("\\", "/").lower()
        # Match folder pattern OR healed filename pattern
        if "/healed/" in normalized or normalized.startswith("healed/") or ".healed.spec.js" in normalized:
            return True
    return False


