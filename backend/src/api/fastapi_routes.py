@router.post("/api/projects/git-init", tags=["Projects"], summary="Initialize git in a project folder")
async def git_init_project_endpoint(body: dict) -> dict[str, Any]:
    import subprocess
    from pathlib import Path

    project_path = (body or {}).get("projectPath")
    github_url = str((body or {}).get("githubUrl") or "").strip()
    if not project_path:
        raise HTTPException(status_code=400, detail="projectPath is required")
    p = Path(project_path)
    if not p.exists() or not p.is_dir():
        raise HTTPException(status_code=400, detail=f"Project folder not found: {project_path}")

    # Run git init (idempotent)
    try:
        result = subprocess.run(
             ["git", "init", "-b", "main"],
            cwd=str(p),
            capture_output=True,
            text=True,
            timeout=30,
        )
        if result.returncode != 0:
            raise HTTPException(status_code=500, detail=f"git init failed: {result.stderr or result.stdout}")
    except FileNotFoundError:
        raise HTTPException(status_code=500, detail="git not found on PATH")
    except subprocess.TimeoutExpired:
        raise HTTPException(status_code=500, detail="git init timed out")

    # If a GitHub URL is provided AND no remote 'origin' yet, set it
    remote_added = False
    remote_error = ""
    if github_url:
        try:
            # Check existing origin
            r_check = subprocess.run(
                ["git", "remote", "get-url", "origin"],
                cwd=str(p),
                capture_output=True,
                text=True,
                timeout=10,
            )
            if r_check.returncode != 0:
                # No origin yet, add it
                r_add = subprocess.run(
                    ["git", "remote", "add", "origin", github_url],
                    cwd=str(p),
                    capture_output=True,
                    text=True,
                    timeout=15,
                )
                if r_add.returncode == 0:
                    remote_added = True
                else:
                    remote_error = (r_add.stderr or r_add.stdout or "").strip()
            else:
                # Origin already exists — just update it
                r_set = subprocess.run(
                    ["git", "remote", "set-url", "origin", github_url],
                    cwd=str(p),
                    capture_output=True,
                    text=True,
                    timeout=15,
                )
                if r_set.returncode == 0:
                    remote_added = True
                else:
                    remote_error = (r_set.stderr or r_set.stdout or "").strip()
        except subprocess.TimeoutExpired:
            remote_error = "git remote command timed out"
        except Exception as _exc:
            remote_error = str(_exc)

        # Also persist the URL in project metadata
        try:
            from .fastapi_support import read_project_metadata, write_project_metadata
            metadata = read_project_metadata(p)
            metadata["githubUrl"] = github_url
            write_project_metadata(p, metadata)
        except Exception as _meta_exc:
            print(f"[git-init] failed to update project metadata: {_meta_exc}")

    # Update DB
    try:
        from ..db.database import set_git_initialized
        updated = set_git_initialized(str(p), value=True)
        return {
            "ok": True,
            "projectPath": str(p),
            "stdout": result.stdout,
            "remote_added": remote_added,
            "remote_error": remote_error,
            "githubUrl": github_url,
            "db": updated or {},
        }
    except Exception as exc:
        return {
            "ok": True,
            "projectPath": str(p),
            "stdout": result.stdout,
            "remote_added": remote_added,
            "remote_error": remote_error,
            "githubUrl": github_url,
            "db_warning": str(exc),
        }

