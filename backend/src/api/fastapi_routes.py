    """Lightweight GET wrapper around the same Jenkins existence check used during POST."""
    job_name = (jobName or "").strip()
    if not job_name:
        return {"ok": True, "exists": False, "message": "", "jenkinsUrl": None, "jobUrl": None}

    jenkins_url = _jenkins_env_value("JENKINS_URL")
    if not jenkins_url:
        return {"ok": False, "exists": False, "message": "JENKINS_URL not configured.", "jenkinsUrl": None, "jobUrl": None}

