async def _run_node_suggester(script_path: Path, payload: dict[str, Any], label: str) -> dict[str, Any]:
    process = await asyncio.create_subprocess_exec(
        resolve_command("node"),
        str(script_path),
        cwd=str(ROOT),
        env=get_run_env(),
        stdin=asyncio.subprocess.PIPE,
        stdout=asyncio.subprocess.PIPE,
        stderr=asyncio.subprocess.PIPE,
    )
    stdout_bytes, stderr_bytes = await process.communicate(json.dumps(payload).encode("utf-8"))
    stdout_text = stdout_bytes.decode("utf-8", errors="replace").strip()
    stderr_text = stderr_bytes.decode("utf-8", errors="replace").strip()

    if process.returncode != 0:
        raise HTTPException(
            status_code=500,
            detail=f"{label} failed: {stderr_text or stdout_text or 'Unknown error.'}",
        )

    if not stdout_text:
        return {}

    try:
        return json.loads(stdout_text)
    except json.JSONDecodeError as exc:
        raise HTTPException(
            status_code=500,
            detail=f"{label} returned invalid JSON: {stdout_text[:500]}",
        ) from exc


