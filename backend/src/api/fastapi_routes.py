def _jenkins_env_value(*names: str) -> str:
    env = get_run_env()
    for name in names:
        value = env.get(name, "").strip()
        if value:
            return value
    return ""


def _jenkins_auth_header() -> str:
    user = _jenkins_env_value("JENKINS_USER", "JENKINS_USERNAME")
    token = _jenkins_env_value("JENKINS_API_TOKEN", "JENKINS_TOKEN")
    if not user or not token:
        return ""
    token_bytes = f"{user}:{token}".encode("utf-8")
    return f"Basic {base64.b64encode(token_bytes).decode('ascii')}"


