@router.get("/api/flakiness", tags=["Workflow"], summary="Get flaky test stats for a project")
async def get_flakiness_endpoint(projectPath: str) -> dict[str, Any]:
    """Return flakiness stats for all tests in the given project, plus summary aggregates."""
    try:
        from ..db.database import get_project_by_path, list_flakiness_for_project, get_flakiness_summary
        project = get_project_by_path(projectPath)
        if not project:
            return {"ok": True, "items": [], "summary": None, "found": False}
        items = list_flakiness_for_project(project["id"])
        summary = get_flakiness_summary(project["id"])
        return {"ok": True, "items": items, "summary": summary, "found": True, "project_id": project["id"]}
    except Exception as exc:
        return {"ok": False, "error": str(exc), "items": [], "summary": None}




